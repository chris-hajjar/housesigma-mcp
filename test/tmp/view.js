const path = require('path');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js');
(async () => {
  const t = new StdioClientTransport({ command: 'node', args: [path.join(__dirname, '..', '..', 'bin', 'stdio.js')], env: { ...process.env }, stderr: 'pipe' });
  const c = new Client({ name: 'view', version: '0' }); await c.connect(t);
  const show = async (n, a = {}, max = 1400) => { const r = await c.callTool({ name: n, arguments: a }); const txt = r.content[0].text; console.log(`\n### ${n} ${JSON.stringify(a)} ${r.isError ? '[ERROR]' : ''} (${txt.length} chars)\n${txt.slice(0, max)}${txt.length > max ? '\n…' : ''}`); return JSON.parse(txt); };
  await show('login');
  const s = await show('search_listings', { where: 'Liberty Village', beds_min: 1, price_max: 3000, limit: 3 });
  const id = s.listings[0].id;
  await show('get_listing', { id }, 2200);
  await show('get_comparables', { id, kind: 'sold' }, 900);
  await show('my_saved', { kind: 'watched', list_type: 'rent' }, 900);
  await show('track_search', { action: 'save', name: 'lv', query: { where: 'Liberty Village', price_max: 3000 } }, 400);
  await show('whats_new', { name: 'lv' }, 400);
  await show('whats_new', { name: 'lv', csv: true }, 700);
  await show('track_search', { action: 'delete', name: 'lv' }, 200);
  await show('market_stats', { kind: 'trend', place: 'Liberty Village', house_type: 'C.', months: 2 }, 1200);
  await show('search_listings', { where: 'Nowhere Special Zzz' }, 300);
  await show('get_listing', { id: 'notreal123' }, 300);
  await c.close();
})().catch(e => { console.error(e); process.exit(1); });
